"""`python -m benchmark check`: run every case's reference calls and check the answer key.
`python -m benchmark run`: put the assistant through every case and score it (score.py).

For each case: every reference call validates and runs; the required caveats appear in the
results; the scenario expectations hold; every fact the answer must cite exists; and every
number the oracle can compute matches it. Needs the database loaded with the dataset the
cases describe (the default synthetic dataset) and that dataset's folder for the oracle.

Writes a Markdown report (default `benchmark/reference-report.md`) and exits 1 on failure.
"""

import argparse
import json
import sys
import time
import uuid
from datetime import date, datetime
from pathlib import Path
from typing import Any

from sqlalchemy import text

from benchmark.agents import clarifying_agent, reference_agent
from benchmark.cases import CASE_SETS, Case, load_cases, resolve
from benchmark.score import citable, expected_facts, score
from benchmark.verify import check_result
from marketingiq.assistant.llm import ModelNotConfigured, get_chat_model
from marketingiq.assistant.paths import Missing
from marketingiq.assistant.run import Run, ask
from marketingiq.db import get_app_engine
from marketingiq.tools import call_tool
from oracle import load

DATASET = Path("data/synthetic/default-seed-20261014")
REPORT = Path("benchmark/reference-report.md")


def _expectation(op: str, actual: Any, wanted: Any) -> bool:
    if op == "equals":
        return str(actual) == str(wanted) if isinstance(actual, date) else actual == wanted
    if op == "contains":
        return wanted in actual
    if op == "startswith":
        return str(actual).startswith(wanted)
    if op == "not_null":
        return actual is not None
    if actual is None or wanted is None:
        return False
    return actual > wanted if op == "gt" else actual < wanted


def run_case(case: Case, engine, org: str, facts) -> dict[str, Any]:
    problems, notes, results, checked = [], [], [], 0
    for call in case.calls:
        try:
            results.append(call_tool(engine, org, call.tool, call.args))
        except Exception as exc:
            problems.append(f"{call.tool} failed: {exc}")
            return {"case": case, "problems": problems, "notes": notes, "checked": 0, "facts": {}}

    codes = {w["code"] for r in results for w in r.get("warnings", [])}
    missing = [code for code in case.warnings if code not in codes]
    if missing:
        problems.append(f"required caveats missing from the results: {missing}")

    for expect in case.expect:
        try:
            actual = resolve(expect.path, results)
            wanted = expect.value
            if isinstance(wanted, str) and wanted.startswith("@"):
                wanted = resolve(wanted[1:], results)
            if not _expectation(expect.op, actual, wanted):
                problems.append(f"expected {expect.path} {expect.op} {wanted!r}, got {actual!r}")
        except Missing as exc:
            problems.append(f"expectation can't be checked: {exc}")

    cited = {}
    for path in case.facts:
        try:
            value = resolve(path, results)
            if value is None or (isinstance(value, dict) and value.get("suppressed")):
                notes.append(f"{path} is hidden or empty: the answer must say so")
            cited[path] = value
        except Missing as exc:
            problems.append(f"fact missing: {exc}")

    for call, result in zip(case.calls, results, strict=True):
        check = check_result(facts, call.tool, call.args, result)
        checked += check.checked
        problems += [f"{call.tool}: {m}" for m in check.mismatches[:5]]
        if len(check.mismatches) > 5:
            problems.append(f"{call.tool}: {len(check.mismatches) - 5} more mismatches")
    return {"case": case, "problems": problems, "notes": notes, "checked": checked, "facts": cited}


def _short(value: Any) -> str:
    text_ = json.dumps(value, default=str)
    return text_ if len(text_) <= 160 else text_[:157] + "..."


def report(outcomes: list[dict], dataset: Path) -> str:
    passed = sum(not o["problems"] for o in outcomes)
    numbers = sum(o["checked"] for o in outcomes)
    lines = [
        "# Benchmark Reference Run",
        "",
        f"Generated by `uv run python -m benchmark check` on `{dataset.as_posix()}`. "
        "Do not edit by hand.",
        "",
        f"**{passed} of {len(outcomes)} cases pass.** {numbers} numbers in the reference "
        "results were recomputed by the oracle.",
        "",
        "| Case | Kind | Scenario | Result | Numbers checked |",
        "| --- | --- | --- | --- | --- |",
    ]
    for o in outcomes:
        case = o["case"]
        result = "pass" if not o["problems"] else "**FAIL**"
        lines.append(
            f"| {case.id} | {case.kind} | {case.scenario or ''} | {result} | {o['checked']} |"
        )
    lines += ["", "## Answer key", ""]
    for o in outcomes:
        case = o["case"]
        lines += [
            f"### {case.id}: {case.question}",
            "",
            f"Kind: {case.kind}. Covers {case.covers}.",
        ]
        if case.calls:
            lines.append("Reference calls: " + ", ".join(f"`{c.tool}`" for c in case.calls) + ".")
        if case.warnings:
            lines.append("Must carry: " + ", ".join(f"`{w}`" for w in case.warnings) + ".")
        if case.forbidden:
            lines.append("Must not say: " + "; ".join(f'"{p}"' for p in case.forbidden) + ".")
        if case.notes:
            lines.append(case.notes)
        if o["facts"]:
            lines += ["", "| Fact | Value |", "| --- | --- |"]
            lines += [f"| `{p}` | `{_short(v)}` |" for p, v in o["facts"].items()]
        for item in o["problems"]:
            lines.append(f"- FAIL: {item}")
        for item in o["notes"]:
            lines.append(f"- Note: {item}")
        lines.append("")
    return "\n".join(lines)


def run_benchmark(args, engine) -> None:
    cases = load_cases(CASE_SETS[args.set])
    if args.cases:
        wanted = set(args.cases.split(","))
        cases = [c for c in cases if c.id in wanted]
    if args.agent == "model":
        try:
            model_name = get_chat_model().name
        except ModelNotConfigured as exc:
            sys.exit(str(exc))
    else:
        model_name = "reference-agent"
    scores = []
    for number, case in enumerate(cases):
        if number and args.delay:
            time.sleep(args.delay)  # stay under free-tier requests per minute
        reference = [call_tool(engine, args.org, c.tool, c.args) for c in case.calls]
        key = expected_facts(case, reference)
        turns = [case.question, *case.followups]
        history: list[tuple[str, str]] = []
        follows = None
        for turn, question in enumerate(turns):
            last = turn == len(turns) - 1
            if args.agent == "model":
                model = get_chat_model()
            elif last:
                model = reference_agent(case, [p for p, v in key.items() if citable(v)])
            else:
                model = clarifying_agent()
            try:
                run = ask(
                    question,
                    engine=engine,
                    org=args.org,
                    model=model,
                    store=args.agent == "model",
                    history=history,
                    follows=follows,
                )
            except Exception as exc:
                run = Run(id=uuid.uuid4(), question=question, model=model.name, errors=[str(exc)])
                break
            history.append((question, run.answer or ""))
            follows = run.id
        result = score(case, run, key)
        scores.append((case, run, result))
        mark = "pass" if result.passed else "FAIL"
        print(
            f"{case.id:5} {mark:4} {run.status:9} facts {result.obtained}/{result.needed}"
            f" cited {result.cited}/{result.citable} {run.latency_ms:6} ms"
        )
    path = args.out or Path("benchmark/runs") / (
        f"{'' if args.set == 'main' else args.set + '-'}"
        f"{model_name.replace('/', '_')}-{datetime.now():%Y%m%d-%H%M}.md"
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(run_report(scores, model_name), encoding="utf-8", newline="\n")
    passed = sum(r.passed for _, _, r in scores)
    print(f"\n{passed}/{len(scores)} cases pass; report: {path}")


def run_report(scores: list, model_name: str) -> str:
    passed = sum(r.passed for _, _, r in scores)
    kinds = sum(r.kind_ok for _, _, r in scores)
    needed = sum(r.needed for _, _, r in scores)
    obtained = sum(r.obtained for _, _, r in scores)
    citable_ = sum(r.citable for _, _, r in scores)
    cited = sum(r.cited for _, _, r in scores)
    failed_runs = sum(run.status == "failed" for _, run, _ in scores)
    lines = [
        f"# Benchmark Run: {model_name}",
        "",
        f"{datetime.now():%Y-%m-%d %H:%M}. Generated by `python -m benchmark run`.",
        "",
        "| Measure | Result |",
        "| --- | --- |",
        f"| Cases passed | {passed} of {len(scores)} |",
        f"| Right kind of response | {kinds} of {len(scores)} |",
        f"| Facts obtained | {obtained} of {needed} |",
        f"| Facts cited | {cited} of {citable_} |",
        f"| Runs that failed the answer contract | {failed_runs} |",
        "| Numbers in answers not traced to a tool | 0 by construction (ADR-006) |",
        "",
        "| Case | Result | Status | Facts | Cited | Missing caveats | Forbidden phrases |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for case, run, r in scores:
        lines.append(
            f"| {case.id} | {'pass' if r.passed else '**FAIL**'} | {run.status} | "
            f"{r.obtained}/{r.needed} | {r.cited}/{r.citable} | "
            f"{', '.join(r.caveats_missing)} | {', '.join(r.forbidden_found)} |"
        )
    lines += ["", "## Answers", ""]
    for case, run, r in scores:
        lines += [
            f"### {case.id}: {case.question}",
            "",
            *[f'Then the user replied: "{reply}"' for reply in case.followups],
            f"Expected: {case.kind}. Got: {run.status}"
            + (" (last turn scored)." if case.followups else "."),
        ]
        lines += ["", f"> {(run.answer or '(no answer)').replace(chr(10), ' ')}", ""]
        tools = ", ".join(f"`{c.tool}`" + ("" if c.ok else " (failed)") for c in run.calls)
        lines.append(f"Tools: {tools or 'none'}.")
        for problem in r.problems:
            lines.append(f"- Run error: {problem}")
        lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m benchmark")
    parser.add_argument("command", choices=["check", "run"])
    parser.add_argument("--dataset", type=Path, default=DATASET)
    parser.add_argument("--org", default="synthetic-home-services")
    parser.add_argument("--report", type=Path, help="answer-key report path for `check`")
    parser.add_argument("--agent", choices=["model", "reference"], default="model")
    parser.add_argument("--cases", help="comma-separated case ids, e.g. Q01,R06")
    parser.add_argument("--set", choices=sorted(CASE_SETS), default="main", help="case set")
    parser.add_argument("--delay", type=float, default=0.0, help="seconds between cases")
    parser.add_argument("--out", type=Path, help="report path for `run`")
    args = parser.parse_args()

    facts = load(args.dataset)
    engine = get_app_engine()
    with engine.connect() as conn:
        as_of = conn.execute(
            text("SELECT data_as_of FROM core.organizations WHERE slug = :org"), {"org": args.org}
        ).scalar()
    if as_of != facts.data_as_of:
        sys.exit(f"The database ({as_of}) and the dataset ({facts.data_as_of}) don't match.")
    if args.command == "run":
        run_benchmark(args, engine)
        return

    cases = load_cases(CASE_SETS[args.set])
    outcomes = [run_case(case, engine, args.org, facts) for case in cases]
    for o in outcomes:
        status = "pass" if not o["problems"] else "FAIL"
        print(f"{o['case'].id:5} {status:4} {o['checked']:5} numbers  {o['case'].question[:70]}")
        for problem in o["problems"]:
            print(f"        {problem}")
    path = args.report or (
        REPORT if args.set == "main" else REPORT.with_name(f"{args.set}-reference-report.md")
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(report(outcomes, args.dataset), encoding="utf-8", newline="\n")
    failed = sum(bool(o["problems"]) for o in outcomes)
    print(f"\n{len(outcomes) - failed}/{len(outcomes)} cases pass; report: {path}")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
